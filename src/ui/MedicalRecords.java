private void loadVisits(List<ClinicVisit> visits) {
    DefaultTableModel model = (DefaultTableModel) tblRecords.getModel();
    model.setRowCount(0);
    for (ClinicVisit v : visits) {
        model.addRow(new Object[]{v.getId(), v.getVisitDate(), v.getStudentName(), v.getComplaint(),
            v.getDiagnosis(), v.getTreatment(), v.getMedicineGiven(), v.getQuantityGiven(), v.getAttendedBy(), v.getRemarks()});
    }
}
