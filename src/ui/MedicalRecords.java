    private void btnFilterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFilterActionPerformed
        // TODO add your handling code here:
    String start = txtStart.getText().trim();
    String end = txtEnd.getText().trim();
    if (start.isEmpty() || end.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter both start and end dates.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }
    loadVisits(visitService.getVisitsBetween(start, end));
    }//GEN-LAST:event_btnFilterActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
         int row = tblRecords.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a record first.");
        return;
    }
    int id = (int) tblRecords.getValueAt(row, 0);
    int confirm = JOptionPane.showConfirmDialog(this, "Move this record to Archives?", "Confirm Archive", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        visitService.archiveVisit(id);
        loadVisits(visitService.getAllVisits());
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

