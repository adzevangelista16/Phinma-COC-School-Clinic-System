    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
            String name = JOptionPane.showInputDialog(this, "Medicine Name:");
    if (name == null || name.trim().isEmpty()) return;
    String category = JOptionPane.showInputDialog(this, "Category:");
    String unit = JOptionPane.showInputDialog(this, "Unit (e.g. tablets, ml):");
    String expiry = JOptionPane.showInputDialog(this, "Expiry Date (yyyy-MM-dd):");
    int stock = 0, reorder = 10;
    try { stock = Integer.parseInt(JOptionPane.showInputDialog(this, "Stock Quantity:", "0")); } catch (Exception ignored) {}
    try { reorder = Integer.parseInt(JOptionPane.showInputDialog(this, "Reorder Level:", "10")); } catch (Exception ignored) {}

    Medicine m = new Medicine(name, category, stock, unit, expiry, reorder);
    if (medicineService.addMedicine(m)) {
        loadMedicines(medicineService.getAllMedicines());
    } else {
        JOptionPane.showMessageDialog(this, "Failed to save. Check your database connection.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
         Medicine m = getSelectedMedicine();
    if (m == null) return;
    int confirm = JOptionPane.showConfirmDialog(this, "Move " + m.getName() + " to Archives?", "Confirm Archive", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        medicineService.archiveMedicine(m.getId());
        loadMedicines(medicineService.getAllMedicines());
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

