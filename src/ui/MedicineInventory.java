    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        Medicine m = getSelectedMedicine();
    if (m == null) return;
    try {
        String stock = JOptionPane.showInputDialog(this, "Stock Quantity:", m.getStockQty());
        if (stock != null) m.setStockQty(Integer.parseInt(stock));
    } catch (Exception ignored) {}
    medicineService.updateMedicine(m);
    loadMedicines(medicineService.getAllMedicines());
    }//GEN-LAST:event_btnEditActionPerformed

