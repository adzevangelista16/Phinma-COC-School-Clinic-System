    private void loadArchivedItems() {
    DefaultTableModel tableModel = (DefaultTableModel) tblArchives.getModel();
    tableModel.setRowCount(0);
    try {
        List<ArchiveItem> items = archiveService.getArchivedItems();
        for (ArchiveItem item : items) {
            tableModel.addRow(new Object[]{
                item.getType(),
                item.getId(),
                item.getDescription(),
                item.getArchivedAt() == null ? "" : item.getArchivedAt().toString()
            });
        }
        lblStatus.setText(items.isEmpty() ? "No archived records found." : "Archived records: " + items.size());
    } catch (IllegalStateException e) {
        lblStatus.setText("Run database/archive_migration.sql, then refresh.");
    }
}

private void restoreSelectedItem() {
    int selectedRow = tblArchives.getSelectedRow();
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "Select an archived record first.");
        return;
    }
    DefaultTableModel tableModel = (DefaultTableModel) tblArchives.getModel();
    int modelRow = tblArchives.convertRowIndexToModel(selectedRow);
    String type = (String) tableModel.getValueAt(modelRow, 0);
    int id = ((Number) tableModel.getValueAt(modelRow, 1)).intValue();
    if (archiveService.restore(type, id)) {
        loadArchivedItems();
        JOptionPane.showMessageDialog(this, "Record restored.");
    } else {
        JOptionPane.showMessageDialog(this, "The record could not be restored.",
                "Restore failed", JOptionPane.ERROR_MESSAGE);
    }
}

