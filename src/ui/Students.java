    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        
        String studentNumber = JOptionPane.showInputDialog(this, "Student Number:");
    if (studentNumber == null || studentNumber.trim().isEmpty()) return;
    String fullName = JOptionPane.showInputDialog(this, "Full Name:");
    if (fullName == null || fullName.trim().isEmpty()) return;
    String grade = JOptionPane.showInputDialog(this, "Grade Level:");
    String section = JOptionPane.showInputDialog(this, "Section:");
    String gender = JOptionPane.showInputDialog(this, "Gender (Male/Female):");
    String birthdate = JOptionPane.showInputDialog(this, "Birthdate (yyyy-MM-dd):");
    String guardianName = JOptionPane.showInputDialog(this, "Guardian Name:");
    String guardianContact = JOptionPane.showInputDialog(this, "Guardian Contact:");
    String allergies = JOptionPane.showInputDialog(this, "Allergies (optional):");

    Student s = new Student(studentNumber, fullName, grade, section, gender, birthdate, guardianName, guardianContact, allergies);
    if (studentService.addStudent(s)) {
        loadStudents(studentService.getAllStudents());
    } else {
        JOptionPane.showMessageDialog(this, "Failed to save. Check your database connection.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAddActionPerformed

