    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        
        Student s = getSelectedStudent();
    if (s == null) return;
    String fullName = JOptionPane.showInputDialog(this, "Full Name:", s.getFullName());
    if (fullName != null) s.setFullName(fullName);
    String grade = JOptionPane.showInputDialog(this, "Grade Level:", s.getGradeLevel());
    if (grade != null) s.setGradeLevel(grade);
    String section = JOptionPane.showInputDialog(this, "Section:", s.getSection());
    if (section != null) s.setSection(section);
    studentService.updateStudent(s);
    loadStudents(studentService.getAllStudents());
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

    Student s = getSelectedStudent();
    if (s == null) return;
    int confirm = JOptionPane.showConfirmDialog(this, "Move " + s.getFullName() + " to Archives?", "Confirm Archive", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        studentService.archiveStudent(s.getId());
        loadStudents(studentService.getAllStudents());
    }
        
        
    }//GEN-LAST:event_btnDeleteActionPerformed

