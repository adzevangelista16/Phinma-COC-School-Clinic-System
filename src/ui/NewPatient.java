    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        Student selectedStudent = (Student) cmbStudent.getSelectedItem();
    if (selectedStudent == null) {
        JOptionPane.showMessageDialog(this, "Please select a student. Add students first if the list is empty.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }
    if (txtComplaint.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter the complaint/reason for visit.", "Missing Info", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Medicine selectedMedicine = (Medicine) cmbMedicine.getSelectedItem();
    int qty = (int) spnQuantity.getValue();

    if (selectedMedicine != null && qty > selectedMedicine.getStockQty()) {
        JOptionPane.showMessageDialog(this, "Not enough stock for " + selectedMedicine.getName() + ". Available: " + selectedMedicine.getStockQty(), "Insufficient Stock", JOptionPane.ERROR_MESSAGE);
        return;
    }

    ClinicVisit visit = new ClinicVisit();
    visit.setStudentId(selectedStudent.getId());
    visit.setComplaint(txtComplaint.getText().trim());
    visit.setDiagnosis(txtDiagnosis.getText().trim());
    visit.setTreatment(txtTreatment.getText().trim());
    visit.setMedicineGiven(selectedMedicine != null ? selectedMedicine.getName() : "");
    visit.setMedicineId(selectedMedicine != null ? selectedMedicine.getId() : null);
    visit.setQuantityGiven(selectedMedicine != null ? qty : 0);
    visit.setAttendedBy(currentUser.getFullName());
    visit.setRemarks(txtRemarks.getText().trim());

    if (new ClinicVisitService().addVisit(visit)) {
        JOptionPane.showMessageDialog(this, "Visit record saved successfully.");
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this, "Failed to save visit. Check your database connection.", "Error", JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_btnSaveActionPerformed

